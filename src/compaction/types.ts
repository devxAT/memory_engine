// ---------------------------------------------------------------------------
// Host messages & the MessageAccessor
// ---------------------------------------------------------------------------

/**
 * Who produced a message. Provider roles are not enough: Anthropic-style APIs put tool
 * results and harness-injected text inside "user" messages.
 */
export type MessageOrigin =
  | "human" // written by the end user; starts a turn
  | "harness" // injected by the host (reminders, steering, notices); never starts a turn
  | "model" // generated by the LLM
  | "tool" // carries tool output
  | "system"; // system / developer instructions

export interface ToolCallInfo {
  /** Required; the host synthesizes one if its provider has none. */
  id: string;
  name: string;
  /** `undefined` when the arguments are not valid JSON. */
  arguments: Record<string, unknown> | undefined;
  /** Original string form, when available. */
  rawArguments?: string;
}

export interface ToolResultInfo {
  toolCallId: string;
  /** Text content of the result (images excluded). */
  text: string;
  imageCount: number;
  isError: boolean;
}

export interface TokenUsage {
  /** Total prompt tokens, including cache reads/writes. */
  inputTokens: number;
  outputTokens: number;
}

/**
 * The engine's only view of the host's message type. Host messages are stored as-is and are
 * never defined, converted, or mutated by the engine.
 */
export interface MessageAccessor<TMsg> {
  getOrigin(msg: TMsg): MessageOrigin;
  getToolCalls(msg: TMsg): ToolCallInfo[];
  getToolResults(msg: TMsg): ToolResultInfo[];
  /**
   * Returns a copy of `msg` whose result for `toolCallId` is replaced by `text`
   * (images dropped). Never mutates.
   */
  replaceToolResult(msg: TMsg, toolCallId: string, text: string): TMsg;
  /**
   * Model-visible text, excluding tool calls/results (the engine renders those) and
   * opaque content.
   */
  toText(msg: TMsg): string;
  /** Builds the message that carries a rendered compaction summary into the context. */
  createSummaryMessage(renderedSummary: string): TMsg;
  /** Optional: provider-reported usage attached to an assistant message. */
  getUsage?(msg: TMsg): TokenUsage | undefined;
  /** Optional: overrides the default heuristic token estimator. */
  estimateTokens?(msg: TMsg): number;
  /** Optional: overrides the default rule `getOrigin(msg) === "human"`. */
  isTurnStart?(msg: TMsg): boolean;
}

// ---------------------------------------------------------------------------
// Session entries
// ---------------------------------------------------------------------------

export interface SessionEntryBase {
  id: string;
  parentId: string | null;
  /** ISO-8601. */
  timestamp: string;
}

export interface MessageEntry<TMsg> extends SessionEntryBase {
  type: "message";
  /** The host's own message type, stored as-is. */
  message: TMsg;
}

export interface CompactionEntry extends SessionEntryBase {
  type: "compaction";
  /** LLM-written text only; deterministic blocks are rendered at build time, never stored here. */
  summary: string;
  firstKeptEntryId: string;
  /** Context tokens at compaction time, as sent to the model. */
  tokensBefore: number;
  /** Estimated tokens of the context rebuilt with this compaction. */
  tokensAfter: number;
  /** Keyed by extractor plugin name. */
  details: Record<string, unknown>;
  reason: "threshold" | "overflow" | "manual";
  /** `PROMPT_VERSION` of the prompts used. */
  promptVersion: string;
  /** Host-supplied model/provider label, for evaluation. */
  summarizerLabel?: string;
}

export interface PruneItem {
  toolCallId: string;
  /** Exact text that replaces the tool result in the context. */
  replacement: string;
  tokensBefore: number;
  tokensAfter: number;
}

export interface PruneEntry extends SessionEntryBase {
  type: "prune";
  strategy: "proactive" | "reactive";
  items: PruneItem[];
}

export type SessionEntry<TMsg> =
  | MessageEntry<TMsg>
  | CompactionEntry
  | PruneEntry
  // Other entry types are ignored by compaction.
  | (SessionEntryBase & { type: string; [key: string]: unknown });

/** Engine output before the session store assigns `id`, `parentId`, and `timestamp`. */
export type NewEntry<E extends SessionEntryBase> = Omit<E, "id" | "parentId" | "timestamp">;

// The catch-all member stops `entry.type === "message"` from narrowing `SessionEntry`,
// so compaction code narrows through these guards.

export function isMessageEntry<TMsg>(entry: SessionEntry<TMsg>): entry is MessageEntry<TMsg> {
  return entry.type === "message";
}

export function isCompactionEntry<TMsg>(entry: SessionEntry<TMsg>): entry is CompactionEntry {
  return entry.type === "compaction";
}

export function isPruneEntry<TMsg>(entry: SessionEntry<TMsg>): entry is PruneEntry {
  return entry.type === "prune";
}

