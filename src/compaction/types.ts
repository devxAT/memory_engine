export interface SummarizeRequest {
  systemPrompt: string;
  /** Serialized transcript + instructions; send as ONE user message. */
  prompt: string;
  maxTokens: number;
  signal?: AbortSignal;
}

/** Host runs the LLM call. The engine never imports an SDK. */
export type SummarizerFn = (request: SummarizeRequest) => Promise<string>;

// ---------------------------------------------------------------------------
// Settings
// ---------------------------------------------------------------------------

export interface PruneRule {
  toolNames: string[];
  /** Overrides the global limit; `Infinity` = never truncate. */
  maxToolResultTokens?: number;
  preserveHeadLines?: number;
  preserveTailLines?: number;
}

export interface CompactionSettings {
  enabled: boolean;
  /** Headroom below the context window; should exceed the host's max output tokens. */
  reserveTokens: number;
  /** Raw tokens kept after the cut point. */
  keepRecentTokens: number;
  /** Max output tokens per summarizer call. */
  summaryMaxTokens: number;
  /** Larger histories are summarized in sequential chunks. */
  maxSummarizerInputTokens: number;
  /** Per-result character cap inside the summarizer transcript. */
  serializerMaxToolResultChars: number;
  micro: {
    strategy: "proactive" | "reactive";
    /** The most recent N tool results are never pruned. */
    keepRecentToolResults: number;
    /** Results above this are truncated. */
    maxToolResultTokens: number;
    preserveHeadLines: number;
    preserveTailLines: number;
    /** Single long lines (e.g. minified JSON) are cut to this length. */
    maxLineChars: number;
    /** Reactive pruning stops at this fraction of the threshold. */
    reactiveTargetRatio: number;
    /** Evict file reads made stale by a later read/modify of the same path. */
    supersededReads: boolean;
    /** Per-tool overrides; first match wins. */
    rules: PruneRule[];
  };
  /** `"hierarchical"` is reserved for Phase 1b. */
  topology: "rolling_delta";
}

